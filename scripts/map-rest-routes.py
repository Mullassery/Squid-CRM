#!/usr/bin/env python3
"""Map every captured REST/OpenAPI route to the current Squid router.

The implemented-route knowledge lives here (not in the fixtures) because the
Rust router is the source of truth. Update IMPLEMENTED when routes are added.

Usage:
  python3 scripts/map-rest-routes.py
"""

import argparse
import json
import os

IMPLEMENTED = {
    "people", "companies", "opportunities", "tasks", "notes",
    "taskTargets", "noteTargets",
}


def classify(spec, path, method):
    if spec == "metadata":
        return "MISSING"
    if path == "/open-api/core":
        return "MISSING"
    parts = [part for part in path.split("/") if part]
    if len(parts) == 1 and parts[0] in IMPLEMENTED:
        return "IMPLEMENTED" if method in ("get", "post") else "MISSING"
    if (
        len(parts) == 2
        and parts[0] in IMPLEMENTED
        and parts[1] == "{id}"
    ):
        return "IMPLEMENTED" if method in ("get", "patch", "delete") else "MISSING"
    if (
        len(parts) == 3
        and parts[0] in IMPLEMENTED
        and parts[1] == "{id}"
        and parts[2] == "restore"
    ):
        return "IMPLEMENTED" if method == "patch" else "MISSING"
    return "MISSING"


def write_markdown(report, out_path):
    lines = [
        "# REST route map",
        "",
        "Generated by `scripts/map-rest-routes.py` from the captured v2.49.0",
        "OpenAPI documents. The core spec is served under `/rest/`; the metadata",
        "spec under `/` (for example `/open-api/metadata`, `/views`).",
        "",
    ]
    for spec, entry in report["specs"].items():
        counts = entry["counts"]
        lines.append(f"## {spec}")
        lines.append("")
        lines.append(
            f"Routes: {entry['routes']} — IMPLEMENTED {counts['IMPLEMENTED']}, "
            f"MISSING {counts['MISSING']}."
        )
        lines.append("")
        lines.append("| Path | Method | Status |")
        lines.append("| --- | --- | --- |")
        for route in entry["operations"]:
            lines.append(
                f"| `{route['path']}` | {route['method'].upper()} | "
                f"**{route['status']}** |"
            )
        lines.append("")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--contracts", default="contracts/v2.50.0")
    parser.add_argument("--out-json", default="contracts/rest-routes.json")
    parser.add_argument("--out-md", default="docs/rest-route-map.md")
    args = parser.parse_args()

    report = {"generatedBy": "scripts/map-rest-routes.py", "specs": {}}
    for spec, filename in (
        ("core", "openapi-core.json"),
        ("metadata", "openapi-metadata.json"),
    ):
        with open(os.path.join(args.contracts, filename)) as fh:
            document = json.load(fh)
        operations = []
        for path, methods in sorted(document.get("paths", {}).items()):
            for method in sorted(methods):
                if method not in ("get", "post", "patch", "delete", "put"):
                    continue
                operations.append(
                    {
                        "path": path,
                        "method": method,
                        "status": classify(spec, path, method),
                    }
                )
        counts = {"IMPLEMENTED": 0, "MISSING": 0}
        for operation in operations:
            counts[operation["status"]] += 1
        report["specs"][spec] = {
            "source": filename,
            "routes": len(operations),
            "counts": counts,
            "operations": operations,
        }

    with open(args.out_json, "w") as fh:
        json.dump(report, fh, indent=2)
    write_markdown(report, args.out_md)
    print(json.dumps({name: entry["counts"] for name, entry in report["specs"].items()}, indent=2))


if __name__ == "__main__":
    main()
